#!/usr/bin/env bash
# clinexia-apply.sh: applies the traction-metrics (web) or in-app-updater (mobile) changes to a Clinexia repo.
#
# Run it from the ROOT of either repo; it detects which one it is from package.json:
#   clinexia-web     -> admin traction dashboard, collectors, backfill + sync scripts, tests, README
#   clinexia-mobile  -> in-app APK updater (Capacitor plugin, flavors, UI, release tooling), tests, README
#
#   bash clinexia-apply.sh              apply the changes (leaves them uncommitted for you to review)
#   bash clinexia-apply.sh --dry-run    only list what would be created or changed
#   bash clinexia-apply.sh --commit     apply, then make small themed git commits
#
# Safe to re-run: new files are rewritten only if different, existing files are patched with exact-match
# anchors (a patch that cannot match is reported and skipped, never half-applied), and anything
# overwritten is first copied to .clinexia-backup/<timestamp>/.
set -euo pipefail

DRY=0; COMMIT=0
for a in "$@"; do
  case "$a" in
    --dry-run) DRY=1 ;;
    --commit) COMMIT=1 ;;
    -h|--help) sed -n '2,16p' "$0"; exit 0 ;;
    *) echo "unknown option: $a" >&2; exit 1 ;;
  esac
done

die() { echo "✗ $*" >&2; exit 1; }
for tool in node tar base64 awk cmp; do command -v "$tool" >/dev/null || die "$tool is required."; done
[ -f package.json ] || die "Run this from the root of a Clinexia repo (no package.json here)."
NAME="$(node -p "require('./package.json').name")"
case "$NAME" in
  clinexia-web) KIND=web ;;
  clinexia-mobile) KIND=mobile ;;
  *) die "Unrecognised repo (package.json name is '$NAME'; expected clinexia-web or clinexia-mobile)." ;;
esac
NODE_MAJOR="$(node -p "process.versions.node.split('.')[0]")"
[ "$NODE_MAJOR" -ge 20 ] || die "Node 20+ is required (found $(node -v))."
[ "$KIND" = web ] && [ "$NODE_MAJOR" -lt 22 ] && echo "⚠ Node 22+ is needed later to run the traction scripts (node --env-file); applying anyway."

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
MARK="$(echo "$KIND" | tr a-z A-Z)"
awk -v b="__CLINEXIA_${MARK}_BEGIN__" -v e="__CLINEXIA_${MARK}_END__" '$0==b{f=1;next} $0==e{f=0} f' "$0" | base64 -d | tar xz -C "$TMP" || die "Could not unpack the embedded files (was this script edited or truncated?)."

echo "▶ Detected: $NAME"
if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  [ -z "$(git status --porcelain --untracked-files=no)" ] || echo "⚠ You have uncommitted changes. Consider committing them first so this change is easy to review."
else
  echo "⚠ Not a git repository: no history to fall back on. Backups go to .clinexia-backup/."
fi

STAMP="$(date +%Y%m%d-%H%M%S)"; BACKUP=".clinexia-backup/$STAMP"; NEW=0; CHANGED=0; SAME=0
cd "$TMP/files"; FILES="$(find . -type f | sed 's#^\./##' | sort)"; cd - >/dev/null
echo "▶ New and updated files"
while IFS= read -r f; do
  src="$TMP/files/$f"
  if [ ! -e "$f" ]; then echo "  + $f"; NEW=$((NEW+1)); [ "$DRY" = 1 ] && continue; mkdir -p "$(dirname "$f")"; cp -p "$src" "$f"
  elif cmp -s "$src" "$f"; then SAME=$((SAME+1))
  else echo "  ~ $f (existing file differs; backup kept)"; CHANGED=$((CHANGED+1)); [ "$DRY" = 1 ] && continue; mkdir -p "$BACKUP/$(dirname "$f")"; cp -p "$f" "$BACKUP/$f"; cp -p "$src" "$f"
  fi
done <<< "$FILES"
echo "  $NEW new, $CHANGED updated, $SAME already up to date"

if [ "$DRY" = 1 ]; then
  echo "▶ Dry run: patches to existing files would be applied from patches.mjs (not run)."
  exit 0
fi

echo "▶ Applying patches"
set +e; node "$TMP/patches.mjs"; PATCH_STATUS=$?; set -e

commit_group() { # message, paths...
  local msg="$1"; shift
  git add -- "$@" 2>/dev/null || true
  git diff --cached --quiet || git commit -q -m "$msg" && true
}

if [ "$COMMIT" = 1 ]; then
  git rev-parse --is-inside-work-tree >/dev/null 2>&1 || die "--commit needs a git repository."
  git diff --cached --quiet || die "Staged changes already exist; commit or unstage them first."
  echo "▶ Committing in small steps"
  if [ "$KIND" = web ]; then
    commit_group "traction: database schema for rollups, installs, search console, APK snapshots and revenue" supabase/traction.sql
    commit_group "traction: pure rollup, retention, GitHub delta and Search Console logic with tests" lib/traction/dates.mjs lib/traction/rollups.mjs lib/traction/github.mjs lib/traction/search-console.mjs lib/traction/rest.mjs lib/traction/csv.mjs lib/traction/rollups.test.ts lib/traction/github.test.ts lib/traction/search-console.test.ts
    commit_group "traction: platform tagging, windows source, visitor-day heartbeat and appinstalled collector" lib/platform.ts lib/analytics app/api/analytics components/analytics-sync.tsx
    commit_group "traction: idempotent backfill and sync scripts plus daily GitHub Actions workflow" scripts/traction .github/workflows/traction-daily.yml package.json
    commit_group "traction: read-only admin dashboard, buyer report, revenue entry and CSV export" app/admin app/api/admin components/admin lib/traction/admin-data.ts lib/admin-login-guard.ts
    commit_group "traction: README setup, backfill and verification guide" README.md
  else
    commit_group "updater: native update plugin, build flavors, FileProvider path and install permission (direct flavor only)" android
    commit_group "updater: version/checksum logic, update dialog, Settings check button, with tests" lib/updater components app/settings/page.tsx
    commit_group "updater: release tooling, version bump, docs and README" scripts docs package.json README.md
  fi
  git diff --quiet && git diff --cached --quiet || echo "⚠ Some changes were left uncommitted (see: git status)."
fi

echo
if [ "$PATCH_STATUS" -ne 0 ]; then
  echo "⚠ Finished with patches that need manual attention (listed above). All new files are in place."
else
  echo "✓ Done."
fi
if [ "$KIND" = web ]; then
cat <<'NEXT'

Next steps (web):
  1. Run supabase/traction.sql in the Supabase SQL editor.
  2. pnpm typecheck && pnpm test
  3. Add the env vars / GitHub secrets listed in README.md ("Traction metrics (admin)").
  4. First data: pnpm traction:rebuild, pnpm traction:github, pnpm traction:gsc-backfill
  5. Add the one-sentence privacy-page update described in README.md, then deploy and open /admin/traction.
NEXT
else
cat <<'NEXT'

Next steps (mobile):
  1. pnpm typecheck && pnpm test
  2. cd android && ./gradlew testDirectDebugUnitTest   (runs the native SHA-256 test; needs the Android SDK)
  3. Build with pnpm release:apk (direct flavor) and test an update on a real phone (see docs/UPDATES.md).
  4. Release flow: pnpm version:bump patch && pnpm release:update --publish
NEXT
fi
[ "$PATCH_STATUS" -eq 0 ] || exit "$PATCH_STATUS"
exit 0
